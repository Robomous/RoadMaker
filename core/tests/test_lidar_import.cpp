std::filesystem::path fixture(const std::string& name) {
  return std::filesystem::path(RM_LIDAR_FIXTURES_DIR) / name;
}

/// The scene frame the fixtures import into: a tmerc on a world origin near the
/// tile, which is what p7-s5's editor form produces.
GeoReference amsterdam_scene() {
  GeoReference geo;
  geo.projection = *tmerc_projection(52.3702, 4.8952);
  return geo;
}

bool mentions(const std::vector<Diagnostic>& diagnostics, std::string_view needle) {
  return std::any_of(diagnostics.begin(), diagnostics.end(), [needle](const Diagnostic& d) {
    return d.message.find(needle) != std::string::npos;
  });
}

/// Points sorted into a canonical order, so two readings of the same tile can be
/// compared without depending on file order.
std::vector<std::array<double, 3>> sorted_points(const PointCloud& cloud) {
  std::vector<std::array<double, 3>> points;
  points.reserve(cloud.size());
  for (std::size_t i = 0; i < cloud.size(); ++i) {
    points.push_back(cloud.point(i));
  }
  std::sort(points.begin(), points.end());
  return points;
}

