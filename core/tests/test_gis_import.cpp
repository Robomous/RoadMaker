// GIS import (p7-s2, #242), asserted against the COMMITTED fixtures in
// core/tests/data/gis (generated by scripts/gen_gis_fixtures.py).
//
// Everything here reads a real file off disk on purpose. Twice before, a
// feature shipped with tests that would have passed on a build which dropped it
// entirely, because no committed fixture exercised it (#324's `<geoReference>`,
// #390's `rm:surface`/`rm:terrain`). A reader tested only against bytes the
// same test just constructed agrees with itself about everything, including its
// mistakes.

