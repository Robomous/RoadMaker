// --- Vector: GeoJSON -------------------------------------------------------

TEST(GisVector, ReadsGeoJsonGeometriesAndNames) {
  const Expected<GisVectorParseResult> result = load_gis_vector(fixture("amsterdam.geojson"));
  ASSERT_TRUE(result.has_value()) << result.error().message;
  const GisVectorLayer& layer = result->layer;

  ASSERT_EQ(layer.features.size(), 3U);
  EXPECT_EQ(layer.features[0].geometry, GisFeature::Geometry::Line);
  EXPECT_EQ(layer.features[0].name, "centre line");
  EXPECT_EQ(layer.features[1].geometry, GisFeature::Geometry::Polygon);
  EXPECT_EQ(layer.features[2].geometry, GisFeature::Geometry::Point);

  // RFC 7946 fixes GeoJSON at WGS84 lon/lat; the reader states that rather than
  // leaving the CRS blank, so the import has something to reproject FROM.
  EXPECT_EQ(parse_crs(layer.crs).kind, CrsKind::Geographic);
  EXPECT_NEAR(layer.bounds[0], 4.8500, 1e-9);
  EXPECT_NEAR(layer.bounds[3], 52.4008, 1e-9);
}

TEST(GisVector, RefusesMalformedJsonWithoutThrowing) {
  const std::filesystem::path path =
      std::filesystem::temp_directory_path() / "rm_gis_broken.geojson";
  std::ofstream(path) << "{ this is not json";
  const Expected<GisVectorParseResult> result = load_gis_vector(path);
  EXPECT_FALSE(result.has_value());
  std::filesystem::remove(path);
}

// --- Vector: Shapefile -----------------------------------------------------

TEST(GisVector, ReadsShapefileGeometryAttributesAndPrj) {
  const Expected<GisVectorParseResult> result = load_gis_vector(fixture("utm31_roads.shp"));
  ASSERT_TRUE(result.has_value()) << result.error().message;
  const GisVectorLayer& layer = result->layer;

  ASSERT_EQ(layer.features.size(), 2U);
  EXPECT_EQ(layer.features[0].geometry, GisFeature::Geometry::Line);
  EXPECT_EQ(layer.features[0].vertices.size(), 3U);
  EXPECT_EQ(layer.features[1].vertices.size(), 2U);
  // The .dbf is cosmetic, but reading it wrong would be silently wrong.
  EXPECT_EQ(layer.features[0].name, "Hoofdweg");
  EXPECT_EQ(layer.features[1].name, "Zijstraat");

  // The sibling .prj is what makes the file locatable at all.
  const Crs crs = parse_crs(layer.crs);
  ASSERT_EQ(crs.kind, CrsKind::TransverseMercator);
  EXPECT_DOUBLE_EQ(crs.lon_0, 3.0);
  EXPECT_DOUBLE_EQ(crs.x_0, 500000.0);

  // Coordinates are read little-endian out of a big-endian-framed record.
  EXPECT_NEAR(layer.features[0].vertices[0][0], 628000.0, 1e-6);
  EXPECT_NEAR(layer.features[0].vertices[0][1], 5804000.0, 1e-6);
}

TEST(GisVector, RefusesAShapefileWhoseCrsIsOutOfFamily) {
  const Expected<GisVectorParseResult> result =
      load_gis_vector(fixture("unsupported_crs_roads.shp"));
  // The FILE reads fine — refusal happens at the transform, where both ends are
  // known and the message can name them.
  ASSERT_TRUE(result.has_value()) << result.error().message;
  const Crs source = parse_crs(result->layer.crs);
  EXPECT_EQ(source.kind, CrsKind::Opaque);

  const Expected<CrsTransform> transform = crs_transform(source, scene_crs(amsterdam_scene()));
  ASSERT_FALSE(transform.has_value());
  // The message must identify the CRS the way the user would recognise it. A
  // WKT elided to its first 80 characters shows only the DATUM boilerplate that
  // every WKT shares — which is what this assertion originally caught.
  // Reported in the ORIGINAL casing the user's .prj carries, not the parser's
  // lowercased working copy.
  EXPECT_NE(transform.error().message.find("NAD27_Texas_North"), std::string::npos)
      << transform.error().message;
  EXPECT_NE(transform.error().message.find("Lambert_Conformal_Conic"), std::string::npos)
      << transform.error().message;
}

// --- Raster: GeoTIFF -------------------------------------------------------

TEST(GisRaster, ReadsAnUncompressedGeoTiffWithItsGeoKeysAndPlacement) {
  const Expected<GisRasterParseResult> result = load_gis_raster(fixture("utm31_image.tif"));
  ASSERT_TRUE(result.has_value()) << result.error().message;
  const GisRaster& raster = result->raster;

  EXPECT_EQ(raster.width, 8);
  EXPECT_EQ(raster.height, 6);
  EXPECT_FALSE(raster.elevation);
  EXPECT_EQ(raster.rgba.size(), 8U * 6U * 4U);
  EXPECT_EQ(parse_crs(raster.crs).kind, CrsKind::TransverseMercator);

  // ModelPixelScale's y is positive in the file and NEGATED here, because
  // raster rows run north to south. Getting this wrong mirrors the image.
  EXPECT_DOUBLE_EQ(raster.transform[0], 10.0);
  EXPECT_DOUBLE_EQ(raster.transform[3], -10.0);
  EXPECT_DOUBLE_EQ(raster.transform[4], 628000.0);
  EXPECT_DOUBLE_EQ(raster.transform[5], 5804000.0);
}

TEST(GisRaster, CompressedGeoTiffsDecodeToTheSamePixelsAsTheUncompressedOne) {
  // This is also what validates the fixture generator's own LZW encoder: a
  // wrong encoder produces a stream that decodes to plausible garbage, and only
  // a comparison against known-good pixels says so.
  const Expected<GisRasterParseResult> plain = load_gis_raster(fixture("utm31_image.tif"));
  ASSERT_TRUE(plain.has_value()) << plain.error().message;

  for (const char* name : {"utm31_image_lzw.tif", "utm31_image_packbits.tif"}) {
    const Expected<GisRasterParseResult> compressed = load_gis_raster(fixture(name));
    ASSERT_TRUE(compressed.has_value()) << name << ": " << compressed.error().message;
    EXPECT_EQ(compressed->raster.rgba, plain->raster.rgba) << name;
  }
}

TEST(GisRaster, RefusesDeflateByNameAndCitesTheFollowUp) {
  // Deflate is refused because ADR-0010 declined zlib, not because the decoder
  // failed — so the message must name the compression and where it is tracked.
  const Expected<GisRasterParseResult> result = load_gis_raster(fixture("utm31_image_deflate.tif"));
  ASSERT_FALSE(result.has_value());
  EXPECT_NE(result.error().message.find("Deflate"), std::string::npos) << result.error().message;
  EXPECT_NE(result.error().message.find("#484"), std::string::npos) << result.error().message;
}

TEST(GisRaster, ReadsAWorldFiledPngIdenticallyToTheSameImageAsGeoTiff) {
  const Expected<GisRasterParseResult> png = load_gis_raster(fixture("utm31_image.png"));
  ASSERT_TRUE(png.has_value()) << png.error().message;
  const Expected<GisRasterParseResult> tif = load_gis_raster(fixture("utm31_image.tif"));
  ASSERT_TRUE(tif.has_value()) << tif.error().message;

  EXPECT_EQ(png->raster.width, tif->raster.width);
  EXPECT_EQ(png->raster.rgba, tif->raster.rgba);
  // Two entirely different georeferencing conventions — GeoTIFF tags and a
  // world file — must land the same image in the same place.
  EXPECT_EQ(png->raster.transform, tif->raster.transform);
  EXPECT_EQ(parse_crs(png->raster.crs).kind, CrsKind::TransverseMercator);
}

